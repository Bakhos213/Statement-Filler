#Requires -Version 5.1
<#
.SYNOPSIS
    Reverses the configuration changes that stop Windows Update from downloading,
    with a full backup taken first.

.DESCRIPTION
    Targets the causes that actually produce "We'll try to download this update
    once you're connected to the internet" on a machine with working internet:

      -FixNcsi      Restore Windows' connectivity detection (NCSI/NLA) so the OS
                    stops believing it is offline.
      -FixMetered   Stop the connection being treated as metered.
      -FixServices  Restore Windows-default startup types for the update and
                    networking service stack, and start what must be running.
      -FixTasks     Re-enable the Update Orchestrator scheduled tasks.
      -FixHosts     Remove hosts-file entries that block Microsoft update domains.
      -RemovePolicy Remove WSUS / "do not connect to internet locations" /
                    pause-update policy values.
      -ResetCaches  Rename SoftwareDistribution and catroot2 (only if not already
                    done).
      -All          Everything above except -ResetCaches.

    Every registry key and file touched is backed up first to a timestamped
    folder, and an Undo.cmd is written into it.

    Run with -WhatIf first to see exactly what would change.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\Repair-WindowsUpdate.ps1 -All -WhatIf

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\Repair-WindowsUpdate.ps1 -All

.NOTES
    MUST be run from an elevated PowerShell prompt.

    If this device is managed by an employer, a domain or an MDM, do not use
    -RemovePolicy without talking to whoever administers it - those policy
    values may be deliberate and will simply be re-applied.
#>

# ConfirmImpact is Medium so a normal run completes without prompting per change.
# Use -WhatIf to preview, or -Confirm to be asked about each one.
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Medium')]
param(
    [switch] $FixNcsi,
    [switch] $FixMetered,
    [switch] $FixServices,
    [switch] $FixTasks,
    [switch] $FixHosts,
    [switch] $RemovePolicy,
    [switch] $ResetCaches,
    [switch] $All,
    [string] $BackupPath = (Join-Path ([Environment]::GetFolderPath('Desktop')) 'WindowsUpdate-Repair-Backup')
)

$ErrorActionPreference = 'Continue'
$ProgressPreference = 'SilentlyContinue'

if ($All) {
    $FixNcsi = $true; $FixMetered = $true; $FixServices = $true
    $FixTasks = $true; $FixHosts = $true; $RemovePolicy = $true
}

if (-not ($FixNcsi -or $FixMetered -or $FixServices -or $FixTasks -or $FixHosts -or $RemovePolicy -or $ResetCaches)) {
    Write-Host ''
    Write-Host '  Nothing selected. Choose one or more switches, or -All.' -ForegroundColor Yellow
    Write-Host '  Run with -? for the full list, and add -WhatIf to preview.' -ForegroundColor Yellow
    Write-Host ''
    return
}

# --- elevation -------------------------------------------------------------
$id = [Security.Principal.WindowsIdentity]::GetCurrent()
$principal = New-Object Security.Principal.WindowsPrincipal($id)
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Host ''
    Write-Host '  This script must be run from an ELEVATED PowerShell prompt.' -ForegroundColor Red
    Write-Host '  Right-click Start > Terminal (Admin), then re-run it.' -ForegroundColor Red
    Write-Host ''
    return
}

# --- backup ----------------------------------------------------------------
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$backupDir = Join-Path $BackupPath $stamp
if ($PSCmdlet.ShouldProcess($backupDir, 'Create backup folder')) {
    New-Item -ItemType Directory -Path $backupDir -Force | Out-Null
}
Write-Host ''
Write-Host "  Backups: $backupDir" -ForegroundColor Cyan

$undoLines = New-Object System.Collections.ArrayList
$null = $undoLines.Add('@echo off')
$null = $undoLines.Add('REM Undo script generated by Repair-WindowsUpdate.ps1')
$null = $undoLines.Add('REM Run this from an elevated Command Prompt to restore the previous state.')
$null = $undoLines.Add('')

function Backup-RegKey {
    param([string] $HivePath, [string] $Label)
    $file = Join-Path $backupDir ("$Label.reg")
    $probe = 'Registry::' + $HivePath
    if (-not (Test-Path -LiteralPath $probe)) {
        Write-Host "    (no key to back up: $HivePath)" -ForegroundColor DarkGray
        return $false
    }
    if ($PSCmdlet.ShouldProcess($HivePath, "Export to $file")) {
        & reg.exe export "$HivePath" "$file" /y | Out-Null
        if ($LASTEXITCODE -eq 0) {
            Write-Host "    backed up $HivePath" -ForegroundColor DarkGray
            $null = $undoLines.Add("reg import `"$file`"")
            return $true
        }
        Write-Host "    WARNING: could not export $HivePath" -ForegroundColor Yellow
    }
    return $false
}

function Set-Reg {
    param([string] $Path, [string] $Name, $Value, [string] $Type = 'DWord')
    if (-not (Test-Path -LiteralPath $Path)) {
        if ($PSCmdlet.ShouldProcess($Path, 'Create registry key')) {
            New-Item -Path $Path -Force | Out-Null
        }
    }
    if ($PSCmdlet.ShouldProcess("$Path\$Name", "Set to $Value")) {
        New-ItemProperty -Path $Path -Name $Name -Value $Value -PropertyType $Type -Force | Out-Null
        Write-Host "    set $Name = $Value" -ForegroundColor Green
    }
}

function Remove-Reg {
    param([string] $Path, [string] $Name)
    if (-not (Test-Path -LiteralPath $Path)) { return }
    $existing = (Get-Item -LiteralPath $Path).GetValue($Name, $null)
    if ($null -eq $existing) { return }
    if ($PSCmdlet.ShouldProcess("$Path\$Name", "Delete (was '$existing')")) {
        Remove-ItemProperty -Path $Path -Name $Name -Force -ErrorAction SilentlyContinue
        Write-Host "    removed $Name (was '$existing')" -ForegroundColor Green
    }
}

# ===========================================================================
if ($FixNcsi) {
    Write-Host ''
    Write-Host '  [1] Network connectivity detection (NCSI / NLA)' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    $ncsi = 'HKLM:\SYSTEM\CurrentControlSet\Services\NlaSvc\Parameters\Internet'
    Backup-RegKey 'HKLM\SYSTEM\CurrentControlSet\Services\NlaSvc\Parameters\Internet' 'NlaSvc-Internet' | Out-Null
    Backup-RegKey 'HKLM\SOFTWARE\Policies\Microsoft\Windows\NetworkConnectivityStatusIndicator' 'NCSI-Policy' | Out-Null

    Set-Reg $ncsi 'EnableActiveProbing' 1 'DWord'

    # Deleting the probe overrides is safer than writing values: Windows then
    # uses its built-in defaults, which stay correct across servicing updates.
    foreach ($n in @('ActiveWebProbeHost', 'ActiveWebProbePath', 'ActiveWebProbeContent',
                     'ActiveDnsProbeHost', 'ActiveDnsProbeContent',
                     'ActiveWebProbeHostV6', 'ActiveWebProbePathV6', 'ActiveWebProbeContentV6',
                     'ActiveDnsProbeHostV6', 'ActiveDnsProbeContentV6')) {
        Remove-Reg $ncsi $n
    }

    # Policy overrides of connectivity checks are a common "debloat" leftover.
    $ncsiPolicy = 'HKLM:\SOFTWARE\Policies\Microsoft\Windows\NetworkConnectivityStatusIndicator'
    if (Test-Path -LiteralPath $ncsiPolicy) {
        if ($PSCmdlet.ShouldProcess($ncsiPolicy, 'Delete NCSI policy key')) {
            Remove-Item -LiteralPath $ncsiPolicy -Recurse -Force -ErrorAction SilentlyContinue
            Write-Host '    removed NCSI Group Policy override key' -ForegroundColor Green
        }
    }

    foreach ($svc in @('nsi', 'netprofm', 'NlaSvc')) {
        if ($PSCmdlet.ShouldProcess($svc, 'Restart service')) {
            try {
                Restart-Service -Name $svc -Force -ErrorAction Stop
                Write-Host "    restarted $svc" -ForegroundColor Green
            } catch {
                try {
                    Start-Service -Name $svc -ErrorAction Stop
                    Write-Host "    started $svc" -ForegroundColor Green
                } catch {
                    Write-Host "    could not restart ${svc}: $($_.Exception.Message)" -ForegroundColor Yellow
                }
            }
        }
    }
}

# ===========================================================================
if ($FixMetered) {
    Write-Host ''
    Write-Host '  [2] Metered connection' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    # a) Allow updates over metered links. This is writable without any
    #    ownership games and immediately unblocks downloads if metering is the
    #    cause - which also proves the diagnosis.
    Backup-RegKey 'HKLM\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate' 'WindowsUpdate-Policy' | Out-Null
    Set-Reg 'HKLM:\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate' 'AllowAutoWindowsUpdateDownloadOverMeteredNetwork' 1 'DWord'

    # b) Repair a tampered machine-wide media cost. Windows itself does not
    #    write Ethernet/WiFi values here; update-blocker tools do. The key is
    #    owned by TrustedInstaller, so ownership has to be taken first.
    $mcPath = 'SOFTWARE\Microsoft\Windows NT\CurrentVersion\NetworkList\DefaultMediaCost'
    Backup-RegKey "HKLM\$mcPath" 'DefaultMediaCost' | Out-Null

    $needsFix = $false
    try {
        $mc = Get-Item -LiteralPath "HKLM:\$mcPath" -ErrorAction Stop
        foreach ($n in @('Ethernet', 'WiFi', 'Default')) {
            $v = $mc.GetValue($n, $null)
            if ($null -ne $v -and [int]$v -ne 1) { $needsFix = $true }
        }
    } catch {
        Write-Host "    could not read DefaultMediaCost: $($_.Exception.Message)" -ForegroundColor Yellow
    }

    if (-not $needsFix) {
        Write-Host '    DefaultMediaCost values are already correct (or unreadable).' -ForegroundColor DarkGray
    } elseif ($PSCmdlet.ShouldProcess("HKLM\$mcPath", 'Take ownership and reset media costs to 1')) {
        try {
            $admins = New-Object System.Security.Principal.SecurityIdentifier('S-1-5-32-544')

            $k = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(
                    $mcPath,
                    [Microsoft.Win32.RegistryKeyPermissionCheck]::ReadWriteSubTree,
                    [System.Security.AccessControl.RegistryRights]::TakeOwnership)
            $acl = $k.GetAccessControl([System.Security.AccessControl.AccessControlSections]::None)
            $acl.SetOwner($admins)
            $k.SetAccessControl($acl)
            $k.Close()

            $k = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(
                    $mcPath,
                    [Microsoft.Win32.RegistryKeyPermissionCheck]::ReadWriteSubTree,
                    [System.Security.AccessControl.RegistryRights]::ChangePermissions)
            $acl = $k.GetAccessControl()
            $rule = New-Object System.Security.AccessControl.RegistryAccessRule(
                        $admins, 'FullControl', 'ContainerInherit', 'None', 'Allow')
            $acl.SetAccessRule($rule)
            $k.SetAccessControl($acl)
            $k.Close()

            foreach ($n in @('Ethernet', 'WiFi', 'Default')) {
                $cur = (Get-Item -LiteralPath "HKLM:\$mcPath").GetValue($n, $null)
                if ($null -ne $cur -and [int]$cur -ne 1) {
                    Set-ItemProperty -Path "HKLM:\$mcPath" -Name $n -Value 1 -Type DWord -Force
                    Write-Host "    DefaultMediaCost\$n : $cur -> 1 (unrestricted)" -ForegroundColor Green
                }
            }
            Write-Host '    A reboot is required for media cost changes to take effect.' -ForegroundColor Yellow
        } catch {
            Write-Host "    Could not reset DefaultMediaCost: $($_.Exception.Message)" -ForegroundColor Yellow
            Write-Host '    Fall back to doing it by hand in regedit (take ownership of the key first):' -ForegroundColor Yellow
            Write-Host "      HKLM\$mcPath" -ForegroundColor Yellow
            Write-Host '      Set Ethernet, WiFi and Default to 1.' -ForegroundColor Yellow
        }
    }

    # c) Per-network metered flag on the current Wi-Fi profile.
    Write-Host ''
    Write-Host '    Also confirm by hand:' -ForegroundColor DarkGray
    Write-Host '      Settings > Network & internet > Wi-Fi > (your network) > Metered connection = OFF' -ForegroundColor DarkGray
    Write-Host '      Settings > Network & internet > Data usage  -> remove any data limit' -ForegroundColor DarkGray
}

# ===========================================================================
if ($FixServices) {
    Write-Host ''
    Write-Host '  [3] Service startup types' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    # Windows 11 defaults. Delayed-start services are set to Automatic here and
    # the delayed flag is written separately.
    $targets = [ordered]@{
        'nsi'          = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'Dhcp'         = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'Dnscache'     = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'NlaSvc'       = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'netprofm'     = @{ Start = 'Manual';    Delayed = $false; MustRun = $true  }
        'NcaSvc'       = @{ Start = 'Manual';    Delayed = $false; MustRun = $false }
        'WlanSvc'      = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'cryptsvc'     = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'gpsvc'        = @{ Start = 'Automatic'; Delayed = $false; MustRun = $true  }
        'AppIDSvc'     = @{ Start = 'Manual';    Delayed = $false; MustRun = $false }
        'bits'         = @{ Start = 'Manual';    Delayed = $false; MustRun = $false }
        'wuauserv'     = @{ Start = 'Manual';    Delayed = $false; MustRun = $false }
        'DoSvc'        = @{ Start = 'Automatic'; Delayed = $true;  MustRun = $true  }
        'UsoSvc'       = @{ Start = 'Automatic'; Delayed = $true;  MustRun = $true  }
        'WaaSMedicSvc' = @{ Start = 'Manual';    Delayed = $false; MustRun = $false }
        'TrustedInstaller' = @{ Start = 'Manual'; Delayed = $false; MustRun = $false }
    }

    # Back up each service key individually - exporting the whole Services hive
    # would produce a needlessly enormous .reg file.
    foreach ($name in $targets.Keys) {
        Backup-RegKey "HKLM\SYSTEM\CurrentControlSet\Services\$name" "Service-$name" | Out-Null
    }

    foreach ($name in $targets.Keys) {
        $meta = $targets[$name]
        $svc = Get-Service -Name $name -ErrorAction SilentlyContinue
        if (-not $svc) {
            Write-Host "    $name : NOT PRESENT on this system" -ForegroundColor Red
            continue
        }

        $current = (Get-CimInstance Win32_Service -Filter "Name='$name'" -ErrorAction SilentlyContinue).StartMode
        $wantMode = 'Auto'
        if ($meta.Start -eq 'Manual') { $wantMode = 'Manual' }

        if ($current -ne $wantMode) {
            if ($PSCmdlet.ShouldProcess($name, "Set startup type $current -> $($meta.Start)")) {
                try {
                    Set-Service -Name $name -StartupType $meta.Start -ErrorAction Stop
                    Write-Host "    $name : startup $current -> $($meta.Start)" -ForegroundColor Green
                } catch {
                    # Protected services (WaaSMedicSvc, sometimes UsoSvc) reject
                    # the service-control path; write the registry value instead.
                    $startVal = 2
                    if ($meta.Start -eq 'Manual') { $startVal = 3 }
                    try {
                        Set-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Services\$name" -Name 'Start' -Value $startVal -Type DWord -Force -ErrorAction Stop
                        Write-Host "    $name : startup set via registry to $($meta.Start) (reboot needed)" -ForegroundColor Green
                    } catch {
                        Write-Host "    $name : could not change startup type - $($_.Exception.Message)" -ForegroundColor Yellow
                    }
                }
            }
        } else {
            Write-Host "    $name : startup already $current" -ForegroundColor DarkGray
        }

        if ($meta.Delayed) {
            Set-Reg "HKLM:\SYSTEM\CurrentControlSet\Services\$name" 'DelayedAutostart' 1 'DWord'
        }

        if ($meta.MustRun -and $svc.Status -ne 'Running') {
            if ($PSCmdlet.ShouldProcess($name, 'Start service')) {
                try {
                    Start-Service -Name $name -ErrorAction Stop
                    Write-Host "    $name : started" -ForegroundColor Green
                } catch {
                    Write-Host "    $name : could not start - $($_.Exception.Message)" -ForegroundColor Yellow
                }
            }
        }
    }

    Write-Host ''
    Write-Host '    Reminder: BITS and wuauserv stopping when idle is NORMAL - they are' -ForegroundColor DarkGray
    Write-Host '    trigger-started. Do not treat that as a fault.' -ForegroundColor DarkGray
}

# ===========================================================================
if ($FixTasks) {
    Write-Host ''
    Write-Host '  [4] Update Orchestrator scheduled tasks' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    try {
        $tasks = Get-ScheduledTask -ErrorAction Stop |
            Where-Object { ($_.TaskPath -like '\Microsoft\Windows\UpdateOrchestrator\*' -or
                            $_.TaskPath -like '\Microsoft\Windows\WindowsUpdate\*') -and
                           $_.State -eq 'Disabled' }
        if (-not $tasks) {
            Write-Host '    No disabled update tasks found.' -ForegroundColor DarkGray
        }
        foreach ($t in $tasks) {
            if ($PSCmdlet.ShouldProcess("$($t.TaskPath)$($t.TaskName)", 'Enable scheduled task')) {
                try {
                    Enable-ScheduledTask -TaskPath $t.TaskPath -TaskName $t.TaskName -ErrorAction Stop | Out-Null
                    Write-Host "    enabled $($t.TaskPath)$($t.TaskName)" -ForegroundColor Green
                    $null = $undoLines.Add("schtasks /Change /TN `"$($t.TaskPath)$($t.TaskName)`" /DISABLE")
                } catch {
                    Write-Host "    could not enable $($t.TaskName): $($_.Exception.Message)" -ForegroundColor Yellow
                }
            }
        }
    } catch {
        Write-Host "    Could not enumerate scheduled tasks: $($_.Exception.Message)" -ForegroundColor Yellow
    }
}

# ===========================================================================
if ($FixHosts) {
    Write-Host ''
    Write-Host '  [5] hosts file' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    $hostsFile = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
    $pattern = 'windowsupdate|delivery\.mp\.microsoft|update\.microsoft|msftncsi|msftconnecttest|dsp\.mp\.microsoft|ws\.microsoft\.com|windows\.com'

    try {
        $lines = Get-Content -LiteralPath $hostsFile -ErrorAction Stop
        $bad = $lines | Where-Object { $_ -notmatch '^\s*#' -and $_ -match '\S' -and $_ -match $pattern }
        if (-not $bad) {
            Write-Host '    No blocking entries found.' -ForegroundColor Green
        } else {
            $backupHosts = Join-Path $backupDir 'hosts.bak'
            if ($PSCmdlet.ShouldProcess($hostsFile, "Remove $($bad.Count) blocking line(s)")) {
                Copy-Item -LiteralPath $hostsFile -Destination $backupHosts -Force
                $null = $undoLines.Add("copy /Y `"$backupHosts`" `"$hostsFile`"")
                foreach ($l in $bad) { Write-Host "    removing: $l" -ForegroundColor Green }
                $kept = $lines | Where-Object { -not ($_ -notmatch '^\s*#' -and $_ -match '\S' -and $_ -match $pattern) }
                Set-Content -LiteralPath $hostsFile -Value $kept -Encoding ASCII -Force
                & ipconfig /flushdns | Out-Null
                Write-Host '    hosts file cleaned and DNS cache flushed.' -ForegroundColor Green
            }
        }
    } catch {
        Write-Host "    Could not process hosts file: $($_.Exception.Message)" -ForegroundColor Yellow
    }
}

# ===========================================================================
if ($RemovePolicy) {
    Write-Host ''
    Write-Host '  [6] Windows Update policy values' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    $cs = Get-CimInstance Win32_ComputerSystem -ErrorAction SilentlyContinue
    if ($cs -and $cs.PartOfDomain) {
        Write-Host "    NOTE: this machine is domain-joined ($($cs.Domain))." -ForegroundColor Yellow
        Write-Host '    Group Policy will re-apply anything removed here at the next refresh.' -ForegroundColor Yellow
    }

    Backup-RegKey 'HKLM\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate' 'WU-Policy-Full' | Out-Null
    Backup-RegKey 'HKLM\SOFTWARE\Policies\Microsoft\Windows\DeliveryOptimization' 'DO-Policy' | Out-Null
    Backup-RegKey 'HKLM\SOFTWARE\Microsoft\WindowsUpdate\UX\Settings' 'WU-UX-Settings' | Out-Null

    $wu = 'HKLM:\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate'
    $au = 'HKLM:\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate\AU'
    $do = 'HKLM:\SOFTWARE\Policies\Microsoft\Windows\DeliveryOptimization'
    $ux = 'HKLM:\SOFTWARE\Microsoft\WindowsUpdate\UX\Settings'

    foreach ($n in @('WUServer', 'WUStatusServer', 'UpdateServiceUrlAlternate',
                     'DoNotConnectToWindowsUpdateInternetLocations', 'DisableWindowsUpdateAccess',
                     'SetPolicyDrivenUpdateSourceForQualityUpdates',
                     'SetPolicyDrivenUpdateSourceForFeatureUpdates',
                     'SetPolicyDrivenUpdateSourceForDriverUpdates',
                     'SetPolicyDrivenUpdateSourceForOtherUpdates',
                     'DeferQualityUpdatesPeriodInDays', 'DeferFeatureUpdatesPeriodInDays',
                     'PauseQualityUpdates', 'PauseFeatureUpdates',
                     'PauseQualityUpdatesStartTime', 'PauseFeatureUpdatesStartTime',
                     'TargetReleaseVersion', 'TargetReleaseVersionInfo',
                     'ExcludeWUDriversInQualityUpdate')) {
        Remove-Reg $wu $n
    }
    foreach ($n in @('UseWUServer', 'NoAutoUpdate', 'AUOptions', 'UseUpdateClassPolicySource')) {
        Remove-Reg $au $n
    }

    # DODownloadMode 100 ("bypass") was removed in Windows 11 and leaves the
    # client with no working download transport.
    $doMode = $null
    if (Test-Path -LiteralPath $do) { $doMode = (Get-Item -LiteralPath $do).GetValue('DODownloadMode', $null) }
    if ($null -ne $doMode -and [int]$doMode -eq 100) {
        Remove-Reg $do 'DODownloadMode'
    }

    # Clear any active pause window.
    foreach ($n in @('PauseUpdatesExpiryTime', 'PauseFeatureUpdatesStartTime', 'PauseFeatureUpdatesEndTime',
                     'PauseQualityUpdatesStartTime', 'PauseQualityUpdatesEndTime',
                     'PausedFeatureStatus', 'PausedQualityStatus', 'PausedFeatureDate', 'PausedQualityDate')) {
        Remove-Reg $ux $n
    }

    if ($PSCmdlet.ShouldProcess('Group Policy', 'Force refresh')) {
        & gpupdate.exe /force | Out-Null
        Write-Host '    Group Policy refreshed.' -ForegroundColor Green
    }
}

# ===========================================================================
if ($ResetCaches) {
    Write-Host ''
    Write-Host '  [7] Update caches' -ForegroundColor White
    Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray

    $sd = Join-Path $env:SystemRoot 'SoftwareDistribution'
    $cr = Join-Path $env:SystemRoot 'System32\catroot2'

    if ((Test-Path "$sd.old") -or (Test-Path "$cr.old")) {
        Write-Host '    Caches already reset previously (.old folders present) - skipping.' -ForegroundColor DarkGray
        Write-Host '    Resetting them again will not help; the fault is not cache corruption.' -ForegroundColor DarkGray
    } elseif ($PSCmdlet.ShouldProcess('SoftwareDistribution and catroot2', 'Stop services and rename caches')) {
        foreach ($s in @('wuauserv', 'bits', 'cryptsvc', 'appidsvc', 'DoSvc', 'UsoSvc')) {
            Stop-Service -Name $s -Force -ErrorAction SilentlyContinue
        }
        Start-Sleep -Seconds 3
        foreach ($pair in @(@($sd, "$sd.$stamp.old"), @($cr, "$cr.$stamp.old"))) {
            if (Test-Path -LiteralPath $pair[0]) {
                try {
                    Rename-Item -LiteralPath $pair[0] -NewName (Split-Path $pair[1] -Leaf) -Force -ErrorAction Stop
                    Write-Host "    renamed $($pair[0])" -ForegroundColor Green
                } catch {
                    Write-Host "    could not rename $($pair[0]): $($_.Exception.Message)" -ForegroundColor Yellow
                }
            }
        }
        foreach ($s in @('cryptsvc', 'appidsvc', 'bits', 'DoSvc', 'UsoSvc', 'wuauserv')) {
            Start-Service -Name $s -ErrorAction SilentlyContinue
        }
    }
}

# ===========================================================================
# Write the undo script and kick off a scan.
# ===========================================================================

if ($PSCmdlet.ShouldProcess('Undo.cmd', 'Write undo script')) {
    $undoFile = Join-Path $backupDir 'Undo.cmd'
    $null = $undoLines.Add('')
    $null = $undoLines.Add('echo Restore complete. Reboot to apply.')
    $null = $undoLines.Add('pause')
    Set-Content -LiteralPath $undoFile -Value $undoLines -Encoding ASCII -Force
    Write-Host ''
    Write-Host "  Undo script: $undoFile" -ForegroundColor Cyan
}

Write-Host ''
Write-Host '  ---------------------------------------------------------------' -ForegroundColor DarkGray
if ($PSCmdlet.ShouldProcess('Windows Update', 'Trigger a scan and download')) {
    Write-Host '  Triggering a fresh scan...' -ForegroundColor White
    & "$env:SystemRoot\System32\UsoClient.exe" StartInteractiveScan 2>$null
    Start-Sleep -Seconds 2
    & "$env:SystemRoot\System32\UsoClient.exe" StartDownload 2>$null
}

Write-Host ''
Write-Host '  NEXT STEPS' -ForegroundColor White
Write-Host '  1. Reboot. Media cost and service startup changes need it.' -ForegroundColor Gray
Write-Host '  2. Check the network icon in the system tray. If it still shows a globe or' -ForegroundColor Gray
Write-Host '     an exclamation mark, Windows still thinks it is offline and updates will' -ForegroundColor Gray
Write-Host '     keep deferring - go back to the NCSI findings.' -ForegroundColor Gray
Write-Host '  3. Re-run Diagnose-WindowsUpdate.ps1 and compare.' -ForegroundColor Gray
Write-Host '  4. If it still will not download, tether to a phone hotspot and retry. That' -ForegroundColor Gray
Write-Host '     single test separates "this PC" from "this network" definitively.' -ForegroundColor Gray
Write-Host ''
